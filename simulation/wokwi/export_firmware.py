#!/usr/bin/env python3
"""Generate browser sketch from production sources without changing their behavior."""
from pathlib import Path
import argparse, hashlib
p=Path(__file__).resolve().parent
root=p.parents[1]
files=['include/board_config.h','include/characters.h','include/mcp_bus.h','include/motion.h','src/motion.cpp','src/main.cpp']
text='// GENERATED by export_firmware.py. Do not edit. Production firmware, no auto-arm.\n'
for name in files:
    data=(root/'firmware/esp32'/name).read_text()
    text+='\n// SOURCE: firmware/esp32/'+name+' SHA256 '+hashlib.sha256(data.encode()).hexdigest()+'\n'
    text+='\n'.join(line for line in data.splitlines() if not line.startswith('#include "') and line!='#pragma once')+'\n'
a=argparse.ArgumentParser();a.add_argument('--check',action='store_true');args=a.parse_args()
out=p/'sketch.ino'
if args.check:
    assert out.read_text()==text,'sketch.ino is stale; run export_firmware.py'
    print('PASS: browser sketch matches production firmware exactly (local includes flattened)')
else: out.write_text(text)
