"""Embed the offline page deterministically. No Node/npm or filesystem upload needed."""
import gzip
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def embed():
    source = (ROOT / 'web/index.html').read_bytes()
    compressed = gzip.compress(source, compresslevel=9, mtime=0)
    rows = [', '.join(f'0x{b:02x}' for b in compressed[i:i+20]) for i in range(0, len(compressed), 20)]
    output = '// Generated by esp32cam/tools/embed_web.py; edit web/index.html.\n#pragma once\n#include <Arduino.h>\n'
    output += 'static const uint8_t kWebGzip[] PROGMEM = {\n  ' + ',\n  '.join(rows) + '\n};\n'
    target = ROOT / 'controller/web_assets.h'
    if not target.exists() or target.read_text(encoding='utf-8') != output:
        target.write_text(output, encoding='utf-8', newline='\n')
    print(f'Offline web: {len(source)} bytes -> {len(compressed)} bytes gzip')
    return compressed


if __name__ == '__main__':
    embed()
