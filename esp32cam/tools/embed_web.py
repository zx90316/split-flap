"""Embed the offline page deterministically. No Node/npm or filesystem upload needed."""
import gzip
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = {
    'kWebGzip': ROOT / 'web/index.html',
    'kWiringRuntimeGzip': ROOT / 'wiring-runtime.svg',
    'kWiringFlashingGzip': ROOT / 'wiring-flashing.svg',
    'kWiringMCPGzip': ROOT / 'wiring-motors.svg',
    'kWiringHallGzip': ROOT / 'wiring-hall.svg',
}


def embed():
    output = '// Generated by esp32cam/tools/embed_web.py; edit the HTML/SVG sources.\n#pragma once\n#include <Arduino.h>\n'
    compressed_page = b''
    for name, path in ASSETS.items():
        source = path.read_bytes()
        compressed = gzip.compress(source, compresslevel=9, mtime=0)
        rows = [', '.join(f'0x{b:02x}' for b in compressed[i:i+20]) for i in range(0, len(compressed), 20)]
        output += f'static const uint8_t {name}[] PROGMEM = {{\n  ' + ',\n  '.join(rows) + '\n};\n'
        if name == 'kWebGzip': compressed_page = compressed
        print(f'Offline {path.name}: {len(source)} bytes -> {len(compressed)} bytes gzip')
    target = ROOT / 'controller/web_assets.h'
    if not target.exists() or target.read_text(encoding='utf-8') != output:
        target.write_text(output, encoding='utf-8', newline='\n')
    return compressed_page


if __name__ == '__main__':
    embed()
